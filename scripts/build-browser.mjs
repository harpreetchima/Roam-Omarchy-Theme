import { cp, lstat, mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { tokenizeBlueprint } from "../src/omarchy/blueprint.mjs";
import { supportedHashes, upstreamCommit } from "../src/omarchy/upstream.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const source = join(root, "browser-extension");
const output = join(root, "dist", "chrome");

async function regularTree(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  for (const entry of entries) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) await regularTree(path);
    else if (!entry.isFile()) throw new Error(`Browser package source must contain regular files, not links: ${relative(root, path)}`);
  }
}

try {
  let manifest;
  try {
    manifest = JSON.parse(await readFile(join(source, "manifest.json"), "utf8"));
  } catch (error) {
    throw new Error("Browser companion source is missing or invalid. Expected browser-extension/manifest.json before running build:browser.", { cause: error });
  }
  if (manifest.manifest_version !== 3) throw new Error("Expected a Manifest V3 browser companion.");
  await regularTree(source);
  const declaredFiles = [
    manifest.background?.service_worker,
    manifest.action?.default_popup,
    ...(manifest.content_scripts ?? []).flatMap((script) => [...(script.js ?? []), ...(script.css ?? [])]),
  ].filter((path) => path && path !== "theme.js");
  for (const path of declaredFiles) {
    const absolute = resolve(source, path);
    if (!absolute.startsWith(source + "/") || !(await lstat(absolute)).isFile()) throw new Error(`Missing browser source file declared by manifest: ${path}`);
  }
  const [blueprint, palette] = await Promise.all([
    readFile(join(root, "src", "themes", "blueprint.css"), "utf8"),
    readFile(join(root, "src", "omarchy", "palette.css"), "utf8"),
  ]);
  const { css, report } = tokenizeBlueprint(blueprint);
  const combined = `${css}\n\n/* Local Omarchy palette roles */\n${palette}`;
  const bundle = `// Generated by scripts/build-browser.mjs. Do not edit.\n` +
    `globalThis.ROAM_OMARCHY_THEME = ${JSON.stringify({ css: combined, supportedHashes, upstreamCommit })};\n`;

  // Remove ONLY the known generated output, after all source preflight checks.
  await mkdir(join(root, "dist"), { recursive: true });
  const dist = await lstat(join(root, "dist"));
  if (!dist.isDirectory() || dist.isSymbolicLink()) throw new Error("Refusing to build through a linked dist directory.");
  await rm(output, { recursive: true, force: true });
  await cp(source, output, { recursive: true });
  await writeFile(join(output, "theme.js"), bundle, "utf8");
  console.log(`Built ${relative(root, output)} (${report.replacements} color fallbacks, ${report.darkMedia} gated OS-dark branches).`);
} catch (error) {
  console.error(`Browser build failed: ${error.message}`);
  process.exitCode = 1;
}
