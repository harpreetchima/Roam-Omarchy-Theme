import { lstat, mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { tokenizeBlueprint } from "../src/omarchy/blueprint.mjs";
import { supportedHashes, upstreamCommit } from "../src/omarchy/upstream.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const source = join(root, "desktop-extension");
const output = join(root, "dist", "desktop");

async function regularFile(path) {
  let entry;
  try { entry = await lstat(path); }
  catch (error) {
    throw new Error(`Missing desktop build input: ${relative(root, path)}. The shared controller must be present before building.`, { cause: error });
  }
  if (!entry.isFile() || entry.isSymbolicLink()) throw new Error(`Expected a regular desktop build input: ${relative(root, path)}`);
  return readFile(path, "utf8");
}

async function outputDirectory(path) {
  await mkdir(path, { recursive: true });
  const entry = await lstat(path);
  if (!entry.isDirectory() || entry.isSymbolicLink()) throw new Error(`Refusing to build through a linked directory: ${relative(root, path)}`);
}

async function writableOutput(path) {
  try {
    const entry = await lstat(path);
    if (!entry.isFile() || entry.isSymbolicLink()) throw new Error(`Refusing to overwrite a non-regular build output: ${relative(root, path)}`);
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
}

try {
  const scripts = [
    join(root, "browser-extension", "protocol.js"),
    join(root, "src", "shared", "style-controller.js"),
    ...["source.js", "storage.js", "ui.js", "adapter.js"].map((name) => join(source, name)),
  ];
  const [classic, blueprint, roles, uiCss, readme] = await Promise.all([
    Promise.all(scripts.map(regularFile)),
    regularFile(join(root, "src", "themes", "blueprint.css")),
    regularFile(join(root, "src", "omarchy", "palette.css")),
    regularFile(join(source, "controls.css")),
    regularFile(join(source, "README.md")),
  ]);
  const { css, report } = tokenizeBlueprint(blueprint);
  const theme = { css: `${css}\n\n/* Local Omarchy palette roles */\n${roles}`, supportedHashes, upstreamCommit };
  const bundle = `// Generated by scripts/build-desktop.mjs. Do not edit.\n` +
    `// Native globals remain readable; all source exports are private to this module.\n` +
    `const scope = new Proxy(Object.create(null), {\n` +
    `  get(target, key) { return Object.hasOwn(target, key) ? target[key] : Reflect.get(globalThis, key, globalThis); }\n` +
    `});\n` +
    classic.map((text, index) => `\n// ${relative(root, scripts[index])}\n(function(globalThis) {\n${text}\n})(scope);\n`).join("") +
    `\nconst theme = ${JSON.stringify(theme)};\nconst uiCss = ${JSON.stringify(uiCss)};\n` +
    `let cleanup = () => {};\nexport default {\n` +
    `  onload({ extensionAPI } = {}) {\n    cleanup();\n` +
    `    cleanup = scope.RoamOmarchyDesktop.createAdapter({ theme, protocol: scope.RoamOmarchyProtocol, styles: scope.RoamOmarchyStyles, uiCss, extensionAPI });\n` +
    `    return cleanup;\n  },\n  onunload() { cleanup(); cleanup = () => {}; }\n};\n`;

  // Check all inputs before touching the two known generated files; no installer runs.
  await outputDirectory(join(root, "dist"));
  await outputDirectory(output);
  await Promise.all([writableOutput(join(output, "extension.js")), writableOutput(join(output, "README.md"))]);
  await writeFile(join(output, "extension.js"), bundle, "utf8");
  await writeFile(join(output, "README.md"), readme, "utf8");
  console.log(`Built ${relative(root, output)} (${report.replacements} color fallbacks, ${report.darkMedia} gated OS-dark branches).`);
} catch (error) {
  console.error(`Desktop build failed: ${error.message}`);
  process.exitCode = 1;
}
